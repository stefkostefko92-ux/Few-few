// server/sitemap.xml — генерира се от самите страници, не се пише на ръка:
//   • всяка server/*.html и server/<език>/index.html без `noindex` (/bye — не);
//   • lastmod = най-новата `dateModified` от JSON-LD на страницата (или „Last updated“ в политиката) —
//     честна дата, не датата на билда; без changefreq/priority (Google ги пренебрегва);
//   • езиковата група (английската + /<език>/) носи взаимните hreflang + x-default, като в <head>.
//
//   node tools/sitemap.mjs           записва server/sitemap.xml
//   node tools/sitemap.mjs --check   само проверява, че е свеж (в tests/site.test.mjs)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRV = join(ROOT, "server");
const BASE = "https://adblock.carbonstealth.eu";
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

const langDirs = readdirSync(SRV, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(SRV, d.name, "index.html"))).map((d) => d.name).sort();
// the English home first, then the other English pages by name, then the language homes
const files = ["index.html", ...readdirSync(SRV).filter((f) => f.endsWith(".html") && f !== "index.html").sort(), ...langDirs.map((d) => `${d}/index.html`)];
const pathOf = (f) => (f === "index.html" ? "/" : f.endsWith("/index.html") ? "/" + f.replace(/index\.html$/, "") : "/" + f.replace(/\.html$/, ""));
const read = (f) => readFileSync(join(SRV, f), "utf8");
const head = (h) => h.slice(0, h.indexOf("</head>"));

function lastmod(f, h) {
  const dates = [...h.matchAll(/"dateModified":\s*"(\d{4}-\d{2}-\d{2})/g)].map((m) => m[1]);
  if (dates.length) return dates.sort().at(-1);
  const m = h.match(/Last updated: (\d{1,2}) ([A-Z][a-z]+) (\d{4})/);
  if (m && MONTHS.includes(m[2])) return `${m[3]}-${String(MONTHS.indexOf(m[2]) + 1).padStart(2, "0")}-${m[1].padStart(2, "0")}`;
  throw new Error(`${f}: no dateModified in JSON-LD and no "Last updated" date — the sitemap needs an honest lastmod`);
}

const pages = files.map((f) => ({ f, h: read(f) })).filter(({ h }) => !/<meta name="robots" content="[^"]*noindex/.test(head(h)));
const cluster = (f) => f === "index.html" || f.endsWith("/index.html");
const alternates = (() => {
  const h = head(read("index.html"));
  return [...h.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)" \/>/g)].map((m) => [m[1], m[2]]);
})();
const esc = (s) => s.replace(/&/g, "&amp;");

const lines = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  "<!-- GENERATED by tools/sitemap.mjs from the pages themselves — do not edit by hand -->",
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
  '        xmlns:xhtml="http://www.w3.org/1999/xhtml"',
  '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
];
for (const { f, h } of pages) {
  lines.push("  <url>", `    <loc>${BASE}${pathOf(f)}</loc>`, `    <lastmod>${lastmod(f, h)}</lastmod>`);
  if (cluster(f)) for (const [lang, href] of alternates) lines.push(`    <xhtml:link rel="alternate" hreflang="${lang}" href="${esc(href)}" />`);
  if (f === "index.html") {
    lines.push("    <image:image>", `      <image:loc>${BASE}/og.png</image:loc>`, "    </image:image>");
    const shot = (h.match(/src="\/(popup-shot\.webp)\?v=/) || [])[1];
    if (shot) lines.push("    <image:image>", `      <image:loc>${BASE}/${shot}</image:loc>`, "    </image:image>");
  }
  lines.push("  </url>");
}
lines.push("</urlset>", "");
const xml = lines.join("\n");

const out = join(SRV, "sitemap.xml");
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== xml) { console.error("server/sitemap.xml is stale — run: node tools/sitemap.mjs"); process.exit(1); }
  console.log(`sitemap: fresh (${pages.length} pages)`);
} else {
  writeFileSync(out, xml);
  console.log(`wrote server/sitemap.xml (${pages.length} pages)`);
}
