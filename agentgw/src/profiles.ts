import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { AGENT_ID_RE } from './keys.js';

export interface AgentProfile {
  id: string;
  name: string;
  title: string;
  tier: 'opus' | 'sonnet';
  /** Публичният профил (Markdown) — част от системния промпт. */
  text: string;
}

const IndexSchema = z.object({
  agents: z.array(
    z.object({
      id: z.string().regex(AGENT_ID_RE),
      name: z.string().min(1),
      title: z.string(),
      tier: z.enum(['opus', 'sonnet']),
    }),
  ),
});

/** Зарежда генерираните публични профили от `agents/` (index.json + <id>.md). */
export function loadProfiles(dir: string): Map<string, AgentProfile> {
  const index = IndexSchema.parse(JSON.parse(readFileSync(join(dir, 'index.json'), 'utf8')));
  const out = new Map<string, AgentProfile>();
  for (const a of index.agents) {
    const text = readFileSync(join(dir, `${a.id}.md`), 'utf8').trim();
    out.set(a.id, { ...a, text });
  }
  return out;
}

