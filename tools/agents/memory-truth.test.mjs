// memory-truth.test.mjs — проверено твърдение за НАШЕТО репо трябва да отразява репото.
//
// Реален дефект (Кръг 2, 2026-08-04): `_memory/konveyera.md` твърдеше като ПРОВЕРЕНО, че
// `softprops/action-gh-release` в cspos.yml е „пинат по подвижен таг, не SHA". Реалността
// (cspos.yml:81) е пълен SHA пин. Изпитателят беше документирал остаряването още на 2026-07-29, но
// лъжливият факт остана в „Проверени поуки" и се инжектираше в Конвейерът при ВСЕКИ старт — агентът
// щеше да „поправя" вече поправено или да докладва фалшива находка.
//
// ЗАЩО ТЕСТЪТ Е ТАКЪВ (три провалени опита преди него, всеки с НОВ фалшив позитив):
//   1) „поука, назоваваща друг агент като остарял" → не различава „X ме опроверга" от „аз опровергавам X";
//   2) „поука, твърдяща непинат по SHA" → хвана СОБСТВЕНАТА ми поправка, която ЦИТИРА старото твърдение;
//   3) същото, с изключение по наличен 40-знаков SHA → хвана поуката на Изпитателя, която описва
//      пина с думи, не с хеш.
// Изводът е този, който сам записах по-рано: разликата „твърдя" срещу „цитирам" в проза е NLP-трудна;
// детектор, който я гадае, вдига шум и хората го изключват. Затова тук НЕ се чете проза изобщо —
// проверява се ПРИСЪСТВИЕТО на верния факт: реалният SHA от workflow-а трябва да го има в паметта.
// Периодичното пресверяване на такива твърдения се носи от `memory-freshness` (срок на годност).

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

test("паметта на Конвейерът отразява РЕАЛНИЯ SHA пин в cspos.yml (не старото „подвижен таг“)", () => {
  const wf = readFileSync(join(ROOT, ".github", "workflows", "cspos.yml"), "utf8");
  const pin = wf.match(/softprops\/action-gh-release@([0-9a-f]{40})/);
  assert.ok(pin, "предпоставка: cspos.yml пинва action-gh-release по пълен SHA (ако това се промени, поуката пак трябва да се обнови)");

  const mem = readFileSync(join(ROOT, ".claude", "agents", "_memory", "konveyera.md"), "utf8");
  const verified = mem.split(/^##\s*Карантина/m)[0];
  assert.ok(verified.includes(pin[1]),
    `паметта на konveyera трябва да носи реалния пин ${pin[1].slice(0, 12)}… — иначе агентът действа по опроверган факт`);
});

// ── Фискални инварианти: памет ↔ код, двупосочно (Кръг 3, 2026-08-04) ────────────────────────────
// Проверих на живо 42-та репо-твърдения на Касаджията: нула счупени пътища, а извадката се оказа
// ВЯРНА (money.ts:9 и erpnet.ts:51 съвпадат дословно). Затова тук не се поправя нищо — заковава се.
// Тези две твърдения не са просто факти за кода: те са ФИСКАЛНИ ИНВАРИАНТИ. Смени ли се кодът,
// едновременно (а) паметта на агента става лъжлива и (б) пада самото изискване. `invariant-check`
// пази дали котвата е В МАТЕРИАЛА на агента; тук се пази дали е ВЯРНА В КОДА.
test("фискален инвариант: закръглянето е СИМЕТРИЧНО half-up (сторно/отстъпки не бива да са асиметрични)", () => {
  const src = readFileSync(join(ROOT, "CSPos", "src", "lib", "money.ts"), "utf8");
  assert.match(src.replace(/\s+/g, " "), /Math\.sign\(\s*value\s*\)\s*\*\s*Math\.round\(\s*Math\.abs\(\s*value\s*\)\s*\)/,
    "roundHalfUp трябва да е Math.sign(v)*Math.round(Math.abs(v)) — иначе отрицателните суми се закръглят асиметрично (памет: kasadjiyata 2026-07-24)");
});

test("фискален инвариант: таймаутът към ФУ остава 45s (човек чака печат/сторно, не бива да се реже)", () => {
  const src = readFileSync(join(ROOT, "CSPos", "src", "lib", "fiscal", "erpnet.ts"), "utf8");
  assert.match(src, /AbortSignal\.timeout\(\s*45_000\s*\)/,
    "ErpNet драйверът трябва да пази 45s таймаут (памет: kasadjiyata 2026-07-24)");
});
