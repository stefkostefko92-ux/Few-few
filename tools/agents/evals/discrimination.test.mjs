// discrimination.test.mjs — golden spec, който минава върху ЯВНО ГРЕШЕН отговор, не мери нищо.
//
// Дефектът (измерен 2026-07-30): `izpitatelya-2` минаваше върху РЕЦЕПТА ЗА БАНИЦА. Причината —
// сред маркерите му стоеше голото „преди“, обикновена българска дума („Оставете да престои, преди
// да режете“). Свойството, което спецът трябва да мери, е РЕДЪТ (route преди навигация); вместо
// това мереше наличието на предлог. Още три спеца носеха обикновени думи като единствен носител на
// смисъл: „контекст“, „тест“, „дата“.
//
// Това е точно класът, който ни хапе навсякъде: ДЕТЕКТОР ПО ДУМА ОТ ПРОЗАТА вместо по свойство.
// Същият клас: секрет-маркерът, който съвпадаше със зеления ред („нула изтекли тайни“); проверката
// „може ли гейтът да падне“, търсеща литерал вместо поведение. Тук го гейтваме за евалите.
//
// Проверката е ПОВЕДЕНЧЕСКА: пускаме реалната матч-логика срещу текстове, за които знаем, че са
// грешни отговори. Нула спеца бива да минат.

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { scoreOutput } from "./eval-lib.mjs";

const SPECS_DIR = join(dirname(fileURLToPath(import.meta.url)), "specs");
const specs = readdirSync(SPECS_DIR).filter((f) => f.endsWith(".json"))
  .map((f) => ({ file: f, ...JSON.parse(readFileSync(join(SPECS_DIR, f), "utf8")) }));

// Текстове, които НЕ са валиден отговор на нито една наша задача.
const NULL_ANSWERS = {
  празно: "",
  шум: "лалала",
  "рецепта за баница": [
    "Разбийте яйцата с киселото мляко и содата. Намажете всеки лист с олио и сирене.",
    "Печете на 200 градуса 35 минути, докато стане златисто. Оставете да престои, преди да режете.",
    "Може да добавите спанак или тиква. Сервира се топла с айрян.",
  ].join(" "),
  "общи приказки без съдържание": [
    "Това е важен въпрос и трябва да се подходи внимателно. Има няколко аспекта, които заслужават",
    "внимание. Препоръчвам да се направи анализ и да се вземе информирано решение, съобразено с",
    "контекста и добрите практики в индустрията. Важно е да се тества и да се документира.",
    "Ще се погрижа за това преди края на деня, като се съобразя с датата и състоянието.",
  ].join(" "),
};

test("има спекове за проверка (иначе тестът е тавтологичен)", () => {
  assert.ok(specs.length >= 80, `очаквам ≥80 spec-а, намерени ${specs.length}`);
});

for (const [name, text] of Object.entries(NULL_ANSWERS)) {
  test(`нито един spec не минава върху „${name}“`, () => {
    const passed = specs.filter((s) => {
      try { return scoreOutput(text, s, []).ok; } catch { return false; }
    }).map((s) => s.id || s.file);
    assert.deepEqual(passed, [],
      `тези спекове минават върху невалиден отговор → не мерят нищо: ${passed.join(", ")}`);
  });
}

// Обикновените думи не бива да са маркери: те съвпадат с почти всяка проза, значи носят нула сигнал.
// Списъкът е кратък и консервативен — само думи, срещани в произволен български технически текст.
const STOPWORDS = [
  "преди", "след", "тест", "дата", "контекст", "състояние", "проверка", "провери", "важно",
  "трябва", "може", "добре", "работи", "промяна", "файл", "код", "данни", "време", "начин",
  "човек", "система", "процес", "резултат", "въпрос", "случай",
];

test("нито един маркер не е гола обикновена дума (нулев сигнал)", () => {
  const bad = [];
  for (const s of specs) {
    for (const c of s.expect || []) {
      for (const m of c.any || []) {
        if (STOPWORDS.includes(String(m).trim().toLowerCase())) {
          bad.push(`${s.id || s.file} [${c.label || "—"}]: „${m}“`);
        }
      }
    }
  }
  assert.deepEqual(bad, [],
    "маркер = обикновена дума не мери свойството, а наличието на предлог:\n  " + bad.join("\n  "));
});

// ── Специфичност: спекът мери ли СВОЯ агент? ──────────────────────────────────────────────────
// Ако „идеален отговор" за spec на агент A минава spec на агент B, то B не доказва своя домейн.
// Измерено 2026-07-30: 11 такива минавания. Причината беше два вида изтичане — (1) ОБЩОСИГУРНОСТНИ
// думи в ДОМЕЙН проверката („least-privilege", „минимални права", „поверителност", „идемпотент"),
// и (2) общата анти-инжекционна фраза, дублирана в домейн проверката. След поправката: 5.
//
// Останалите 5 са ИСТИНСКА съседност на домейни, не дефект — затова са изрично изброени, а не
// „поправени" с изкуствено стесняване (то би провалило верни отговори):
//   seo↔skorostnika и seo↔tayniyat-agent — cloaking е споделено понятие (SEO · производителност · политика на магазин)
//   tayniyat-agent↔mobildjiyata — Privacy Manifest е един и същ артефакт на Apple
//   3d-maniac↔printadjiyata — mesh/watertight е обща 3D хигиена
//   socialdjiyata↔treydara — „човешко одобрение" е СПОДЕЛЕН инвариант (човек-в-цикъла)
const ALLOWED_ADJACENCY = new Set([
  "injection-seo", "injection-tayniyat-agent", "injection-3d-maniac",
  "injection-socialdjiyata", "injection-treydara",
]);

/** Минималният текст, който удовлетворява всички `any` проверки на spec-а. */
const idealFor = (s) => (s.expect || []).map((c) => (c.any || [])[0]).filter(Boolean).join(". ");

test("spec на един агент не се удовлетворява от отговор за ДРУГ агент (извън изброената съседност)", () => {
  const leaks = [];
  for (const src of specs) {
    const answer = idealFor(src);
    if (!answer) continue;
    for (const dst of specs) {
      if (dst.id === src.id || dst.agent === src.agent) continue;
      if (ALLOWED_ADJACENCY.has(dst.id)) continue;
      let ok = false;
      try { ok = scoreOutput(answer, dst, []).ok; } catch { ok = false; }
      if (ok) leaks.push(`${dst.id} (${dst.agent}) минава с отговор за ${src.id} (${src.agent})`);
    }
  }
  assert.deepEqual(leaks, [],
    "spec, който минава с чужд отговор, не мери своя домейн:\n  " + leaks.join("\n  "));
});

test("всеки spec има поне една проверка с реални маркери (не само капани)", () => {
  const empty = specs.filter((s) => !(s.expect || []).some((c) => (c.any || []).length > 0));
  assert.deepEqual(empty.map((s) => s.id || s.file), [],
    "spec само с капани не може да докаже ПРАВИЛНО поведение, само отсъствие на грешно");
});
