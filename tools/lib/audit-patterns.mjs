// Защо отделен модул: `test-audit.mjs` и `doc-audit.mjs` са CLI скриптове — тялото им тича при
// import (чете дървото, накрая `process.exit`). Затова предикатите им не можеха да се тестват на
// място. И двата вече са ЛЪГАЛИ веднъж по същия начин: колекторът/регексът пропускаше или
// прехващаше грешното, а одиторът докладваше „чисто". Одитор без регресия върху собствения си
// разпознавател е декорация. Тук са чисти функции, без I/O → tools/lib/audit-patterns.test.mjs.

import { extname } from "node:path";

export const TEST_EXT = new Set([".js", ".ts", ".tsx", ".jsx", ".mjs", ".cjs"]);

// Кой файл се брои за тестов (Изпитателят). До 2026-07-27 шаблонът НЕ включваше `.e2e.`, затова
// `medqr/test/webauthn.e2e.mjs` и подобните бяха сляпо петно — нито `.only`, нито flaky проверките
// са ги гледали някога, а итогът пишеше „няма чести тестови проблеми".
export const isTestFile = (name) =>
  TEST_EXT.has(extname(name)) && /\.(test|spec|e2e)\.|(^|\/)__tests__\//.test(name);

// Недовършен маркер в публикуван документ (Летописецът). `XXX{2,}` с флаг `i` ловеше `xxxx` в
// примерни команди → фалшиви позитиви, които удавяха истинския сигнал. Стеснено до ГЛАВНИ X, които
// НЕ са част от име на файл/идентификатор: `backup-XXXX.sql.gz` е примерен аргумент (не е находка),
// а `+359 XX XXX XXXX` в правен документ е истински незапълнен плейсхолдър (е находка).
export const isUnfinished = (ln) =>
  /\b(TODO|TBD|FIXME|WIP)\b|lorem ipsum|<placeholder>/i.test(ln) ||
  /(?<![-_/\w])XXX+(?![-_.\w])/.test(ln);
