// Потвърждение на имейл по връзка от писмото — кога важи (чисто, тества се).
// Разбивача F1 (#446) затвори това само за адреси, които ВЕЧЕ са в ADMIN_EMAILS; Н8
// (2026-11-21): адрес, добавен в списъка ПО-КЪСНО, наследява потвърждение, направено от
// скенер/клик без сесия → чужд акаунт с наш адрес става админ. Затова връзката важи само в
// сесията на СЪЩИЯ потребител — за всеки адрес. Скенерите в пощата не потвърждават нищо.
export function verifyEmailAllowed(pendingUserId: string, sessionUserId: string | null | undefined): boolean {
  return typeof sessionUserId === 'string' && sessionUserId === pendingUserId;
}
