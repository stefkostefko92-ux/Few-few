// Типове за каталога на държавните предприятия.
//
// Философията на модела е да опише СТРУКТУРАТА на паричните потоци — откъде
// влизат и къде излизат парите на всяко предприятие — по коректен и проверим
// начин, вместо да гони конкретни годишни суми (те се менят всяка година и се
// проверяват в официалните източници, посочени за всяко предприятие).

/** Правна форма по Търговския закон / специален закон. */
export type LegalForm =
  | "ЕАД" // еднолично акционерно дружество (100% държавен капитал)
  | "АД" // акционерно дружество (държавата е акционер)
  | "ЕООД" // еднолично дружество с ограничена отговорност
  | "ООД"
  | "ДП"; // държавно предприятие (по чл. 62, ал. 3 ТЗ или специален закон)

/** Сектор на дейност (виж sectors.ts за пълните описания). */
export type SectorKey =
  | "energetika"
  | "transport"
  | "saobshteniya"
  | "otbrana"
  | "industriya"
  | "finansi-uslugi"
  | "gori-zemedelie"
  | "vodi-ekologiya"
  | "zdraveopazvane"
  | "kultura-media"
  | "hazart"
  | "regionalno";

/** Кой упражнява правата на държавата (принципал). Виж principals.ts. */
export type PrincipalKey =
  | "energetika"
  | "transport"
  | "ikonomika"
  | "inovacii"
  | "otbrana"
  | "zemedelie"
  | "rrb"
  | "finansi"
  | "sport"
  | "kultura"
  | "osv"
  | "zdrave"
  | "ms";

/** Един паричен поток — входящ или изходящ. */
export type MoneyFlow = {
  /** Кратко име на потока, напр. „Продажба на електроенергия“. */
  label: string;
  /** По-подробно обяснение (по избор). */
  note?: string;
  /** Груб дял/тежест за визуален индикатор: 1 = основен, 2 = значим, 3 = второстепенен. */
  weight?: 1 | 2 | 3;
};

/** Официален източник за проверка на данните. */
export type Source = {
  label: string;
  url: string;
};

/**
 * Ориентировъчен финансов маркер. Използва се пестеливо и САМО с ясна година и
 * източник; когато липсва сигурност, полето се пропуска и разчитаме на връзките
 * към официалните регистри.
 */
export type FinancialNote = {
  year: string;
  /** Свободен текст, напр. „приходи ~2,1 млрд. лв. (група)“. */
  text: string;
  source?: Source;
};

export type Enterprise = {
  /** URL идентификатор (кирилица → латиница). */
  slug: string;
  /** Официално наименование. */
  name: string;
  /** Съкращение/абревиатура. */
  shortName?: string;
  legalForm: LegalForm;
  /** Дял на държавата в капитала (%). */
  stateShare: number;
  /** ЕИК — само когато е потвърден; иначе се пропуска. */
  eik?: string;
  sector: SectorKey;
  principal: PrincipalKey;
  /** Дружество-майка (за холдингови структури), по име. */
  parent?: string;
  /** Седалище. */
  hq?: string;
  /** Официален сайт — само когато домейнът е потвърден. */
  website?: string;
  /** Какво прави предприятието (1–3 изречения). */
  activity: string;
  /** Защо съществува / стратегическа роля. */
  role: string;
  /** Как влизат парите. */
  moneyIn: MoneyFlow[];
  /** Как излизат парите. */
  moneyOut: MoneyFlow[];
  /** Кой контролира и одитира. */
  oversight: string[];
  /** Известни рискове за прозрачност/управление (само проверими, внимателно). */
  notes?: string[];
  financial?: FinancialNote;
  sources: Source[];
};
