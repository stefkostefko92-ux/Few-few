// Връща клиент само ако е конфигуриран ключ; иначе чатът деградира любезно.
export function getClient(): Anthropic | null {
  const key = process.env.ANTHROPIC_API_KEY;
  if (!key) return null;
  return new Anthropic({ apiKey: key });
}

