-- Котвата на одитната верига (прегледът за сигурност, 25.09.2026).
--
-- Веригата `hmacPrecedente` лови изтрит ред ПО СРЕДАТА, но не и изтрити
-- ПОСЛЕДНИ редове: няма следващо звено, което да се счупи. Котвата пази
-- последното звено на всяка фирма, подписано с ключа на одита — тя се пише от
-- приложението при всяко вписване и не може да бъде пренаписана без ключа.
--
-- Празна при миграцията: подпис в SQL няма как да се сложи (ключът не е в
-- базата). Първото вписване на всяка фирма я създава; дотогава проверката
-- казва „котва липсва", не „цялост нарушена".

CREATE TABLE "audit_ancore" (
    "chiave" TEXT NOT NULL,
    "seq" BIGINT NOT NULL,
    "hmac" TEXT NOT NULL,
    "firma" TEXT NOT NULL,
    "aggiornataAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "audit_ancore_pkey" PRIMARY KEY ("chiave")
);
