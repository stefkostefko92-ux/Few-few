-- Една степен на покана — най-много веднъж на фактура.
--
-- ЗАЩО В БАЗАТА, А НЕ САМО В МАРШРУТА. Маршрутът чете колко покани са
-- изпратени, смята коя е следващата и записва — три стъпки, между които има
-- прозорец. Двоен клик по бавна връзка минава два пъти през него и ражда два
-- реда „primo sollecito". Таблицата е само-добавяща (доказателство, не
-- работен запис), тоест дубликатът не се маха после: остава в историята на
-- вземането и се вижда от длъжника.
-- ДУБЛИТЕ ВЕЧЕ СЪЩЕСТВУВАТ — точно затова има миграция.
--
-- Индексът върху таблица, в която състезанието вече е родило два реда, пада с
-- 23505: `prisma migrate deploy` връща ненулев код, контейнерът не тръгва, а
-- `_prisma_migrations` остава с ред `failed`, който блокира и всяко следващо
-- разгръщане до ръчна намеса. Затова почистването е В СЪЩАТА миграция.
--
-- ПАЗИ СЕ НАЙ-СТАРИЯТ ред: таблицата е доказателство, а първата покана е тази,
-- която длъжникът е получил. По-късният дубликат е артефакт от двойния клик.
DELETE FROM "solleciti" a
USING "solleciti" b
WHERE a."fatturaId" = b."fatturaId"
  AND a."livello" = b."livello"
  AND (a."createdAt", a."id") > (b."createdAt", b."id");

CREATE UNIQUE INDEX "solleciti_fatturaId_livello_key"
  ON "solleciti" ("fatturaId", "livello");
