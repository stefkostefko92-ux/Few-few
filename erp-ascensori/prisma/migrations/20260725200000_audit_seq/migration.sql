-- Монотонен ред на вписване в одита.
--
-- `createdAt` не става за подредба на веригата: две операции в една и съща
-- милисекунда се сортират произволно и проверката обявява счупена верига там,
-- където нищо не е пипано. Освен това добавянето вече се СЕРИАЛИЗИРА с
-- `pg_advisory_xact_lock` по фирма (виж `scriviAudit`) — иначе два едновременни
-- записа получават един и същ предходник.

ALTER TABLE "audit_log" ADD COLUMN "seq" BIGSERIAL;
CREATE UNIQUE INDEX "audit_log_seq_key" ON "audit_log"("seq");
