-- Час на започване на превоза върху DDT — чл. 1, ал. 3 D.P.R. 472/1996.
--
-- Дотогава документът носеше само дата. Датата не оправдава превоза: два
-- камиона по същия маршрут в същия ден се покриват от една товарителница, а
-- при пътна проверка часът е това, което свързва документа с конкретния курс.
--
-- Полето е NULLABLE и това е нарочно: старите DDT не могат да получат час със
-- задна дата, а фискален документ не се пренаписва. Проверката за пълнота
-- (`validaDdt`) го иска само за новите.
ALTER TABLE "ddt" ADD COLUMN "inizioTrasporto" TIMESTAMP(3);
