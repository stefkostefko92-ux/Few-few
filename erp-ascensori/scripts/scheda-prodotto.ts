/** Първият намерен шрифт с кирилица. Липсата му е грешка, не изненада. */
function trovaFont(varianti: string[]): string {
  for (const p of varianti) if (existsSync(p)) return p;
  throw new Error(
    `Шрифт с кирилица не е намерен. Търсени: ${varianti.join(", ")}. ` +
      "Инсталирай fonts-dejavu-core.",
  );
}

