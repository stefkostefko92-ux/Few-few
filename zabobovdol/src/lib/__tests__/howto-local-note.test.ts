import test from "node:test";
import assert from "node:assert/strict";
import { parseLocalNote } from "@/lib/howto-local-note";

const NOI = `В Бобов дол няма офис на НОИ. Най-близо са:
• Офис Дупница — ул. „Св. Иван Рилски“ № 1, тел. 0882 91 23 30 (отдел „Пенсии“), приемно време 8:00–16:30 ч.
• ТП на НОИ Кюстендил — ул. „България“ № 46, тел. 0700 14 802 (национален), приемно време 08:00–16:30 ч.
Преди да тръгнете, се обадете. Източник: nssi.bg (Контакти → Териториални поделения → Кюстендил), проверено на 23.10.2026.`;

test("parseLocalNote: абзац, списък с „•“ и отделен ред за източника", () => {
  assert.deepEqual(parseLocalNote(NOI), [
    { kind: "p", text: "В Бобов дол няма офис на НОИ. Най-близо са:" },
    {
      kind: "ul",
      items: [
        "Офис Дупница — ул. „Св. Иван Рилски“ № 1, тел. 0882 91 23 30 (отдел „Пенсии“), приемно време 8:00–16:30 ч.",
        "ТП на НОИ Кюстендил — ул. „България“ № 46, тел. 0700 14 802 (национален), приемно време 08:00–16:30 ч.",
      ],
    },
    { kind: "p", text: "Преди да тръгнете, се обадете." },
    {
      kind: "source",
      text: "Източник: nssi.bg (Контакти → Териториални поделения → Кюстендил), проверено на 23.10.2026.",
    },
  ]);
});

test("parseLocalNote: няколко абзаца с източник във всеки; без източник — както е", () => {
  const two = "А: тел. 0702 6 34 69. Източник: asp.government.bg, проверено на 23.10.2026.\n\nБ без източник.";
  assert.deepEqual(parseLocalNote(two), [
    { kind: "p", text: "А: тел. 0702 6 34 69." },
    { kind: "source", text: "Източник: asp.government.bg, проверено на 23.10.2026." },
    { kind: "p", text: "Б без източник." },
  ]);
  assert.deepEqual(parseLocalNote(""), []);
  assert.deepEqual(parseLocalNote("Източник: x.bg"), [{ kind: "source", text: "Източник: x.bg" }]);
});
