async function main() {
  let upd = 0;
  for (const it of updates) {
    try { await prisma.faq.update({ where: { slug: it.slug }, data: { answer: it.answer, steps: it.steps.join("\n"), ...(it.tags ? { tags: it.tags } : {}) } }); upd++; }
    catch { console.error(`Пропуснат: ${it.slug}`); }
  }
  console.log(`✔ Обновени: ${upd}/${updates.length}`);
}
main().catch((e) => { console.error(e); process.exit(1); }).finally(() => prisma.$disconnect());
