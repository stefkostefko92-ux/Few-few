async function main() {
  // --- Услуга: EasyPay офис ---
  const service = {
    name: "EasyPay — плащане на сметки и данъци (в брой)",
    category: "ADMIN" as const,
    description: easypayDescription,
    address: "ул. „27 октомври“, бл. 22, гр. Бобов дол",
    phone: "0894 690570",
    phone2: "0700 20 787",
    hours: "Пон–Пет 09:00–18:00; Събота 10:00–16:00",
    website: "https://www.easypay.bg/site/?p=offices",
    order: 20,
    published: true,
  };
  await prisma.service.upsert({
    where: { slug: "easypay-bobov-dol" },
    update: service,
    create: { slug: "easypay-bobov-dol", ...service },
  });
  console.log("✔ Услуга: EasyPay (Бобов дол)");

  // --- Ръководство: как да платя на каса ---
  const guide = {
    question: "Как да платя сметки, данъци и глоби на каса (EasyPay)?",
    category: "Документи и плащания",
    answer: guideAnswer,
    steps: guideSteps,
    tags: "easypay, плащане, сметки, данъци, глоби, каса, в брой",
    order: 50,
    published: true,
  };
  await prisma.faq.upsert({
    where: { slug: "kak-da-platya-na-kasa-easypay" },
    update: guide,
    create: { slug: "kak-da-platya-na-kasa-easypay", ...guide },
  });
  console.log("✔ Ръководство: плащане на каса (EasyPay)");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
