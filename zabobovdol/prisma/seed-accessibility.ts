async function main() {
  for (const g of guides) {
    const data = {
      question: g.question,
      answer: g.answer,
      category: CAT,
      tags: g.tags ?? "",
      steps: g.steps ? g.steps.join("\n") : "",
      order: g.order,
      published: true,
    };
    await prisma.faq.upsert({
      where: { slug: g.slug },
      update: data,
      create: { slug: g.slug, ...data },
    });
  }
  console.log(`✔ Достъпност (ръководства): ${guides.length}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
