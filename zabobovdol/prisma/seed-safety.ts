// Привежда и съществуващото ръководство за онлайн измами към същата категория.
async function consolidate() {
  await prisma.faq.updateMany({
    where: { slug: "kak-da-razpoznavam-onlayn-izmami" },
    data: { category: SAFETY },
  });
}

async function main() {
  for (const g of guides) {
    const data = { ...g, published: true };
    await prisma.faq.upsert({ where: { slug: g.slug }, update: data, create: data });
  }
  await consolidate();
  console.log(`✔ Ръководства за безопасност и пари: ${guides.length}`);
  console.log("Готово.");
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
