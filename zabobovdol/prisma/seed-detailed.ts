async function main() {
  let ok = 0;
  for (const it of items) {
    try {
      await prisma.faq.update({
        where: { slug: it.slug },
        data: {
          answer: it.answer,
          steps: it.steps.join("\n"),
          ...(it.tags ? { tags: it.tags } : {}),
          ...(it.relatedLinks ? { relatedLinks: it.relatedLinks.join("\n") } : {}),
        },
      });
      ok++;
    } catch (e) {
      console.error(`Пропуснат (липсва?): ${it.slug}`);
    }
  }
  console.log(`✔ Обогатени ръководства: ${ok}/${items.length}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
