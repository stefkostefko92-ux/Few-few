async function main() {
  let upd = 0;
  for (const it of updates) {
    try {
      await prisma.faq.update({
        where: { slug: it.slug },
        data: {
          answer: it.answer,
          steps: it.steps.join("\n"),
          ...(it.tags ? { tags: it.tags } : {}),
        },
      });
      upd++;
    } catch {
      console.error(`Пропуснат (липсва?): ${it.slug}`);
    }
  }
  let created = 0;
  for (const it of newOnes) {
    const data = {
      question: it.question!,
      category: it.category ?? "Здраве и грижа",
      answer: it.answer,
      steps: it.steps.join("\n"),
      tags: it.tags ?? "",
      order: it.order ?? 100,
      published: true,
    };
    await prisma.faq.upsert({
      where: { slug: it.slug },
      update: data,
      create: { slug: it.slug, ...data },
    });
    created++;
  }
  console.log(`✔ Обновени: ${upd}/${updates.length}, нови: ${created}/${newOnes.length}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
