async function main() {
  let fixed = 0;
  let current = 0;
  let skipped = 0;
  for (const f of FIXES) {
    const row = await prisma.faq.findUnique({
      where: { slug: f.slug },
      select: { id: true, question: true, answer: true, steps: true },
    });
    if (!row) {
      console.log(`  – ${f.slug}: няма го в базата — пропускам`);
      skipped++;
      continue;
    }
    const now = row[f.field];
    if (now === f.to) {
      current++;
      continue;
    }
    if (now !== f.from) {
      console.log(`  ! ${f.slug} (${f.field}): текстът е различен (ръчна редакция?) — не го пипам`);
      skipped++;
      continue;
    }
    const data =
      f.field === "question" ? { question: f.to } : f.field === "answer" ? { answer: f.to } : { steps: f.to };
    await prisma.faq.update({ where: { id: row.id }, data });
    console.log(`  ✓ ${f.slug} (${f.field})`);
    fixed++;
  }
  console.log(`✔ Остарели текстове: поправени ${fixed}, вече верни ${current}, пропуснати ${skipped}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
