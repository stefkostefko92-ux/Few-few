async function main() {
  for (const g of guides) {
    const data = { ...g, published: true };
    await prisma.faq.upsert({ where: { slug: g.slug }, update: data, create: data });
  }
  console.log(`✔ Основни ръководства за телефона: ${guides.length}`);
  console.log("Готово.");
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });
