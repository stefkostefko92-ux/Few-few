import type { Role } from "./session";

/**
 * Кой какво може — разделение на функциите, не украса.
 *
 * Ролите съществуваха преди този модул, но не се прилагаха никъде. Това е
 * по-лошо от липсата им: интерфейсът обявява разделение, каквото системата не
 * налага, и одиторът получава фалшива увереност.
 *
 * Ключовото решение е, че **одиторът НЕ прави справки.** Човекът, който
 * проверява законосъобразността на чуждите справки, не бива да е и източник на
 * такива — иначе проверява себе си. Обратно, заявителят не чете дневника:
 * дневникът е за надзор, не за оперативна работа, а достъпът до него показва
 * кой какво разследва.
 *
 * Чист модул. Проверката се прави на ВСЯКО място, което върши действието, а не
 * само в интерфейса: скрит бутон не е ограничение.
 */

export type Capability =
  /** Справка за адрес — основната работа. */
  | "lookup"
  /** Активна проверка към целта. Демаскира разследването, затова е отделна. */
  | "probe"
  /** Замразяване за преписка. */
  | "freeze"
  /** Четене и проверка на одиторския дневник. */
  | "readAudit";

const MATRIX: Record<Role, readonly Capability[]> = {
  operator: ["lookup", "probe", "freeze"],
  // Ръководителят работи оперативно И вижда дневника на структурата си —
  // самоконтролът по чл. 25 е негово задължение, не само на външен одитор.
  supervisor: ["lookup", "probe", "freeze", "readAudit"],
  // Само надзор. Няма справки: който проверява законосъобразността, не бива да
  // е и източник на проверяваното.
  auditor: ["readAudit"],
};

export function can(role: Role, capability: Capability): boolean {
  return MATRIX[role]?.includes(capability) ?? false;
}

/** Какво може ролята — за интерфейса, който не бива да предлага невъзможното. */
export function capabilitiesOf(role: Role): readonly Capability[] {
  return MATRIX[role] ?? [];
}

/** Съобщението при отказ. Еднакво навсякъде, за да не издава структурата. */
export const DENIED_MESSAGE =
  "Ролята ти не позволява това действие. Разделението на функциите е нарочно и се проверява на сървъра.";
