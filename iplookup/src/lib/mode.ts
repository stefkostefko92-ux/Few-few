/**
 * Два режима, един код.
 *
 * `public` — безплатният сайт: нула съхранение, нула автентикация, страниците с
 * резултат са `noindex`. Обещанията в политиката за поверителност важат.
 *
 * `investigation` — вътрешно издание за правоприлагащ орган. Различава се
 * КОРЕННО, не козметично: изисква автентикация, води одиторски дневник и
 * показва следствената справка. Тези изисквания идват от режима за обработване
 * за правоприлагащи цели, а не от предпочитание.
 *
 * Режимът е ЕДИН за целия процес и се задава от средата на сървъра. Няма
 * превключване по заявка — иначе публичен посетител би могъл да си поиска
 * следствения изглед.
 *
 * ВАЖНО: включването на този флаг само по себе си НЕ прави продукта годен за
 * доставка на МВР. То отключва интерфейса; автентикацията, одиторският дневник
 * и договорът за обработване са отделна работа и без тях режимът не бива да
 * се пуска в мрежа. Виж `SECURITY.md` → „Следствено издание".
 */

export type Mode = "public" | "investigation";

export function currentMode(env: Record<string, string | undefined> = process.env): Mode {
  return env.IPLOOKUP_MODE === "investigation" ? "investigation" : "public";
}

export function isInvestigationMode(env?: Record<string, string | undefined>): boolean {
  return currentMode(env) === "investigation";
}
