/**
 * Два режима, един код.
 *
 * `public` — безплатният сайт: нула съхранение, нула автентикация, страниците с
 * резултат са `noindex`. Обещанията в политиката за поверителност важат.
 *
 * `investigation` — вътрешно издание за правоприлагащ орган. Различава се
 * КОРЕННО, не козметично, и то в неочаквана посока.
 *
 * ── Защо следственият режим пита ПО-МАЛКО, а не повече ──────────────────
 *
 * Първият инстинкт е обратният: за разследване искаш максимум източници. Но
 * всяка ЖИВА справка издава кого разследваш.
 *
 * · RDAP заявката отива при регистъра (ARIN, APNIC, RIPE) — те логват заявките,
 *   и то извън ЕС.
 * · Geofeed заявката отива ПРАВО на сървъра на оператора на заподозрения. Тоест
 *   самата проверка казва на отсрещната страна, че някой се интересува от този
 *   префикс.
 * · Активната проверка отваря връзка към целта — тя вижда нашия адрес.
 *
 * Това е едновременно предаване към трета държава (глава V от Директива
 * (ЕС) 2016/680) и оперативен теч. Затова тук по подразбиране работи само
 * това, което не напуска сървъра, а живите източници са изрично действие с
 * предупреждение — не мълчалива подразбираща се стъпка.
 *
 * ВАЖНО: флагът НЕ прави продукта годен за доставка на МВР. Липсват
 * автентикация, одиторски дневник (чл. 25 от Директивата — задължителен, и
 * пълна обратна страна на публичния дизайн) и договор по чл. 22(3). Виж
 * `SECURITY.md` → „Следствено издание".
 */

export type Mode = "public" | "investigation";

export interface Capabilities {
  /** Живи справки към регистрите (RDAP, Cymru). */
  liveRegistry: boolean;
  /** Сваляне на geofeed файла на оператора — най-издайническата заявка. */
  geofeed: boolean;
  /** Активна проверка към целта. */
  activeProbe: boolean;
  /** Показва ли се следствената справка. */
  caseBrief: boolean;
  /** Изисква ли режимът одиторски дневник, за да е законосъобразен. */
  auditRequired: boolean;
}

export function currentMode(env: Record<string, string | undefined> = process.env): Mode {
  return env.IPLOOKUP_MODE === "investigation" ? "investigation" : "public";
}

export function isInvestigationMode(env?: Record<string, string | undefined>): boolean {
  return currentMode(env) === "investigation";
}

/**
 * Какво е позволено в текущия режим.
 *
 * Издайническите източници се включват само с изричен флаг на средата, за да е
 * невъзможно да се появят „случайно" при инсталация по подразбиране. Решението
 * да се поеме рискът е на органа, не на кода.
 */
export function capabilities(env: Record<string, string | undefined> = process.env): Capabilities {
  if (currentMode(env) === "public") {
    return {
      liveRegistry: true,
      geofeed: true,
      activeProbe: true,
      caseBrief: false,
      auditRequired: false,
    };
  }
  return {
    // Регистърът е нужен, за да знаеш КОМУ да пишеш — без него справката е
    // безполезна. Остава включен, но интерфейсът казва, че оставя следа.
    liveRegistry: true,
    geofeed: env.IPLOOKUP_ALLOW_GEOFEED === "1",
    activeProbe: env.IPLOOKUP_ALLOW_PROBE === "1",
    caseBrief: true,
    auditRequired: true,
  };
}
