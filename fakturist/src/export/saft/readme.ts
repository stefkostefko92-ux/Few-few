import type { SaftAccounts } from './model.js';
import type { SaftBundle } from './bundle.js';

/** README.txt в архива: какво има, по какво е съставено и какво трябва да сверите преди внос. */
export function saftReadme(input: {
  orgName: string;
  period: string;
  accounts: SaftAccounts;
  bundle: SaftBundle;
}): string {
  const { bundle, accounts } = input;
  const lines = [
    `Данни за SAF-T — ${input.orgName}, ${input.period}`,
    '',
    'Продажбите за месеца като фрагменти по схемата на НАП за SAF-T, версия 1.0.3',
    '(BG_SAFT_Schema_V_1.0.3.xsd), за внос в счетоводната програма, която съставя и подава месечния файл.',
    'Всеки файл е отделен елемент от схемата и минава проверка срещу нея. Фактурист не подава SAF-T.',
    '',
    'Файлове:',
    ...bundle.files.map((f) => `  ${f.name}`),
    '',
    `Документи: ${bundle.included} · клиенти: ${bundle.customers} · артикули: ${bundle.products}`,
    `Сметки: вземания от клиенти ${accounts.receivable}, приходи ${accounts.revenue}`,
    '',
    'Как е съставено:',
    '- Сумите са в евро; при документ в друга валута — и във валутата, с курса на документа.',
    '- DebitCreditIndicator по „Въпроси и отговори“ на НАП (в. 2, S.I.47): D — редът увеличава',
    '  вземането; C — намалява го с положителна сума (кредитно известие, отстъпка, приспаднат аванс).',
    '- TaxType 100 и TaxCode 100211 (20 %) / 100213 (9 %); InvoiceType 01 фактура и авансова фактура,',
    '  02 дебитно известие, 03 кредитно известие; CustomerID с префикс (10 ЕИК, 11 ДДС номер от ЕС,',
    '  12 регистров номер извън ЕС, 13 ЕГН, 14/15 собствен код). Сверете ги с Приложение 2 на НАП',
    '  (SAF-T_BG_Structure_Definition.xlsx) — при разлика важи номенклатурата на НАП.',
    '- TransactionID е номерът на документа: използвайте същия при осчетоводяването му.',
    '- Отстъпката и надбавката за целия документ са отделни редове (артикули FKT-DISCOUNT и FKT-CHARGE).',
    '- Салдата на клиентите са само по документите и плащанията, въведени във Фактурист. Авансовите',
    '  фактури не влизат (окончателната ги приспада); анулиран документ е в сила до деня на анулирането.',
    '  Счетоводната програма ги смята от главната книга — те имат предимство.',
    '- Свързаните лица са по списъка, въведен във Фактурист („Данни за SAF-T“).',
  ];
  if (bundle.manual.length > 0) {
    const reasons: Record<string, string> = {
      category:
        'категория на ДДС без сверен код (0 %, освободена, обратно начисляване, извън обхвата)',
      type: 'вид документ, който не влиза в продажбите',
      cancelled: 'анулиран — отразява се според указанията на счетоводителя',
    };
    lines.push('', 'Не са във файловете — за ръчно въвеждане:');
    for (const m of bundle.manual) lines.push(`  ${m.number} — ${reasons[m.reason] ?? m.reason}`);
  }
  return `${lines.join('\r\n')}\r\n`;
}
