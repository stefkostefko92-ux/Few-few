-- Дневниците по ДДС стават функция от регистъра (`vat-ledgers`, SPEC 99) — „проверява се“ до проверката с
-- инструментите на НАП. Досега бяха достъпни на всеки план, затова кодът се добавя към всеки съществуващ план
-- (само там, където го няма — повторното пускане не дублира). Без промяна на схемата.
UPDATE "Plan"
SET "features" = array_append("features", 'vat-ledgers')
WHERE NOT ('vat-ledgers' = ANY("features"));
