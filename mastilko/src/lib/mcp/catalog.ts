/**
 * Текстовете за търсене, изчислени ВЕДНЪЖ при зареждане на модула. Преди се
 * смаляваха при всяка заявка за всичките 14 записа — постоянни ~57 µs, които
 * не зависят от заявката и нямат нужда да се плащат всеки път.
 */
const HAYSTACK = CATALOG.map((e) => ({
  e,
  id: e.id.toLowerCase(),
  title: e.title.toLowerCase(),
  aliases: e.aliases.join(" · ").toLowerCase(),
  text: e.text.toLowerCase(),
}));

/**
 * Повече думи от това не помагат на търсене из 14 записа, а цената расте
 * линейно: 200 думи = ~576 µs, 16 думи = ~89 µs (мерено). Без таван една
 * заявка с дълъг низ беше най-евтиният начин да се натовари сървърът.
 */
const MAX_QUERY_WORDS = 16;

/** Търсене по заглавие, идентификатор, синоними и текст — с подредба по тежест. */
export function searchCatalog(query: string, limit = 10): CatalogEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return CATALOG.slice(0, limit);
  // Кирилицата няма смислен stemming тук, затова търсим по думи-подниза:
  // достатъчно е за каталог от 14 записа и не иска зависимост.
  const words = q.split(/\s+/).filter(Boolean).slice(0, MAX_QUERY_WORDS);

  const scored = HAYSTACK.map((hay) => {
    let score = 0;
    for (const w of words) {
      if (hay.id === w || hay.title === w) score += 100;
      else if (hay.title.includes(w)) score += 40;
      else if (hay.aliases.includes(w)) score += 30;
      else if (hay.id.includes(w)) score += 20;
      else if (hay.text.includes(w)) score += 8;
    }
    return { e: hay.e, score };
  }).filter((x) => x.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((x) => x.e);
}

export function catalogById(id: string): CatalogEntry | undefined {
  return CATALOG.find((e) => e.id === id);
}
