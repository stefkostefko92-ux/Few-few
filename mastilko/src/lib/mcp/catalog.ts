// Каталог на 14-те инструмента на Мастилко — единственият източник на истина
// за `search` и `fetch` в MCP конектора.
//
// Защо съществува отделно от `registry.ts`: инструментите за СЪЗДАВАНЕ покриват
// 13 от 14-те (снимките за документи искат качено изображение, което асистент
// не може да подаде), но ТЪРСЕНЕТО трябва да намира всичките 14 — иначе
// режимът за проучване на ChatGPT не може да ни цитира за нещо, което правим.
//
// `url` е задължително непразен: ChatGPT прави цитат само когато резултатът
// носи адрес. Без него отговорът минава за обикновен изход от инструмент.

export interface CatalogEntry {
  /** Стабилен идентификатор — това е и `id`-то, което `fetch` приема. */
  id: string;
  title: string;
  url: string;
  /** Пълният текст, който `fetch` връща — отговор отпред, после подробности. */
  text: string;
  /** Думи, по които хората търсят същото нещо (виж „Наричат го още“ в сайта). */
  aliases: string[];
}

const BASE = "https://mastilko-bg.com";

function entry(
  id: string,
  title: string,
  text: string,
  aliases: string[],
): CatalogEntry {
  return { id, title, url: `${BASE}/${id}`, text: text.trim(), aliases };
}

