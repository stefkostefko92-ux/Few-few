// Български типографски автокоректор — оправя правите кавички на „ … “,
// многоточието, тиретата и излишните интервали. Чисто клиентско, без мрежа.
// Прилага се по изричен бутон (не автоматично), за да не изненадва потребителя.

export function fixBgTypography(input: string): string {
  let t = input;

  // Многоточие: три или повече точки → „…“ (един знак).
  t = t.replace(/\.{3,}/g, "…");

  // Двойни прави кавички → редуващи се „ (отваряща) и “ (затваряща).
  let open = true;
  t = t.replace(/"/g, () => {
    const q = open ? "„" : "“";
    open = !open;
    return q;
  });

  // Двойно тире → дълго тире (—); тире между интервали → късо тире (–).
  t = t.replace(/--/g, "—");
  t = t.replace(/ - /g, " – ");

  // Изтрий интервал ПРЕДИ пунктуация.
  t = t.replace(/ +([,.!?;:…])/g, "$1");

  // Свий поредни интервали/табове до един (без да пипаш новите редове).
  t = t.replace(/[ \t]{2,}/g, " ");

  // Махни интервали в края на всеки ред.
  t = t.replace(/[ \t]+$/gm, "");

  return t;
}
