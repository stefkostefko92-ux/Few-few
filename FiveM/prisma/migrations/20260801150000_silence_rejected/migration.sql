-- Изчиства профила на вече свалените по чл. 21 ОРЗД канали.
--
-- Досега свалянето сменяше само `status`, а името, адресът, заглавието на
-- предаването и броят зрители оставаха — тоест обработването НЕ беше
-- прекратено, а политиката обещава „само платформата и името на канала“.
-- Поправката в кода важи отсега нататък; този ред чисти заварените.
UPDATE "Streamer"
SET "displayName" = '',
    "profileUrl"  = '',
    "streamTitle" = NULL,
    "language"    = NULL,
    "viewers"     = 0,
    "live"        = false,
    "lastLiveAt"  = NULL,
    "lastSeenAt"  = NULL
WHERE "status" = 'REJECTED';
