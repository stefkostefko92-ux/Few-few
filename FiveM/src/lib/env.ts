/**
 * Четене на стойност от околната среда, устойчиво на празни кавички.
 *
 * ЗАЩО СЪЩЕСТВУВА, измерено, не предположено. `env_file` на Docker Compose НЕ
 * маха обгръщащите кавички — стойността минава буквално. Тоест ред
 * `TWITCH_CLIENT_ID=""` стига до приложението като ДВУЗНАКОВИЯ низ `""`, който
 * е ИСТИНЕН. Всяка проверка от вида `if (!key) return []` минава покрай него и
 * кодът тръгва да работи с боклук вместо да пропусне платформата чисто.
 *
 * Същата причина вече счупи веднъж админ панела: `ADMIN_PASSWORD_HASH="соль:хеш"`
 * се четеше с кавичките, `split(':')` даваше `"соль` и `хеш"`, и ВЯРНАТА парола
 * получаваше „Грешна парола“ завинаги.
 *
 * `.env.example` вече пише празните стойности БЕЗ кавички, но файлът се копира
 * на ръка и се редактира на ръка — затова четенето също не бива да им вярва.
 */
export function readEnv(name: string): string | undefined {
  const raw = process.env[name];
  if (raw === undefined) return undefined;
  const cleaned = raw.trim().replace(/^["']|["']$/g, '').trim();
  return cleaned === '' ? undefined : cleaned;
}
