// Текстови помощници за СЪРВЪРНАТА страна.
//
// Отделен файл, а не внос от `public/`: браузърният код и сървърният живеят в
// различни светове (единият е модул за браузър, другият за Node) и споделянето
// им би вързало двете страни за нищо. Функцията е седем реда — дублирането ѝ е
// по-евтино от свързването.
//
// Тези низове НЕ са само за екрана: те тръгват и към Telegram, имейла и
// седмичния отчет. „1 дни до изтичане" в известие за сертификат изглежда точно
// толкова небрежно, колкото и в панела.

// Съгласуване по число: в българския „1" иска ЕДИНСТВЕНО число.
export function plural(n, one, many) {
  return `${n} ${Number(n) === 1 ? one : many}`;
}
