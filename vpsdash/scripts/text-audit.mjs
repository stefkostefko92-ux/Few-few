#!/usr/bin/env node
// Одит на ТЕКСТА: съгласуване по число, типография, единна терминология.
//
// Защо машинно: интерфейсът има над хиляда низа на три езика. „1 точки" не чупи
// нищо, не пада тест и не се вижда в код-ревю — вижда се само от човека, който
// го чете на екрана, и подкопава доверието точно в момента, в който панелът
// трябва да звучи авторитетно.
//
// Проверява се само това, което има ЕДИН верен отговор. Стилът (кое звучи
// по-добре) остава за човека.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const hard = [];
const soft = [];

const files = [
  ...fs.readdirSync(path.join(ROOT, 'public')).filter((f) => f.endsWith('.js')).map((f) => `public/${f}`),
  ...fs.readdirSync(path.join(ROOT, 'src')).filter((f) => f.endsWith('.js')).map((f) => `src/${f}`),
  'public/index.html',
].map((f) => ({ f, text: fs.readFileSync(path.join(ROOT, f), 'utf8') }));

// ── 1. Съгласуване по число ──────────────────────────────────────────────────
// В българския „1" иска ЕДИНСТВЕНО число. Шаблон `${n} точки` дава „1 точки"
// винаги, когато броят е едно — а той е едно точно в най-честия случай:
// прясно пуснат панел, първи запис, единствен диск.
const PLURALS = {
  точки: 'точка', записа: 'запис', секции: 'секция', дни: 'ден', часа: 'час',
  минути: 'минута', файла: 'файл', реда: 'ред', пъти: 'път', контейнера: 'контейнер',
  услуги: 'услуга', правила: 'правило', сесии: 'сесия', задачи: 'задача',
  аларми: 'аларма', ядра: 'ядро', пакета: 'пакет', домейна: 'домейн', сайта: 'сайт',
  възела: 'възел', канала: 'канал', проверки: 'проверка', архива: 'архив',
  таймера: 'таймер', порта: 'порт', образа: 'образ', тома: 'том',
};
// БЕЗ `\b` накрая: границата на дума в JavaScript е ASCII-базирана, значи
// между „точки" и интервал НЕ съвпада (и двата знака са „не-дума" за нея).
// Първата версия на този одит беше зелена точно затова — при видим на екрана
// дефект „1 точки". Същият капан вече ни се случи и в одита на документите.
const PLURAL_RX = new RegExp(`\\$\\{[^}]{1,60}\\}\\s+(${Object.keys(PLURALS).join('|')})(?![а-яА-Я])`, 'g');
for (const { f, text } of files) {
  for (const m of text.matchAll(PLURAL_RX)) {
    // Ред-коментар не е интерфейс. Дефиницията на помощника ОПИСВА дефекта в
    // собствения си текст („`${n} точки` дава 1 точки") — тя е решението, не
    // случаят.
    const lineStart = text.lastIndexOf('\n', m.index) + 1;
    if (/^\s*(\/\/|\*)/.test(text.slice(lineStart, m.index))) continue;
    // Извикване на помощника значи, че случаят вече е решен.
    const before = text.slice(Math.max(0, m.index - 120), m.index);
    if (/plural\(/.test(before)) continue;
    const line = text.slice(0, m.index).split('\n').length;
    hard.push(`${f}:${line} — „${m[0].trim()}" дава „1 ${m[1]}" при брой едно (иска се „${PLURALS[m[1]]}")`);
  }
}

// ── 2. Типография — СЪЗНАТЕЛНО НЕ се проверява ───────────────────────────────
// Опитах два подхода и нито един не различава ТИПОГРАФИЯ от СИНТАКСИС:
//   · „всяка права кавичка в показван текст" вдига 24 фалшиви тревоги, защото
//     цитираният код е прав по право („slo.enabled": false е JSON);
//   · „права кавичка около българска дума" вдига `title="Меню"` и `aria-label=
//     "Затвори"` — там правата кавичка Е синтаксисът на HTML.
// Проверка, която съобщава синтаксис за дефект, учи човека да не чете доклада —
// това е по-скъпо от липсващата проверка. Кавичките остават за човешко око.

// ── 3. Двойни интервали и празнина преди пунктуация ─────────────────────────
for (const { f, text } of files) {
  // Точка, следвана от БУКВА, е разширение на файл („.env", „.deb", „.bak") —
  // не пунктуация. Първата версия ги броеше за дефекти и трупаше шум, а шумният
  // гейт се изключва.
  for (const m of text.matchAll(/(?:text|title|body):\s*'[^']*?(  +|\s+[,;:!?]|\s+\.(?![\w-]))[^']*'/g)) {
    const line = text.slice(0, m.index).split('\n').length;
    hard.push(`${f}:${line} — двоен интервал или празнина преди пунктуация: „${m[0].slice(0, 70)}"`);
  }
}

// ── 4. Единна терминология ───────────────────────────────────────────────────
// Един и същ обект с две имена кара човека да се чуди дали са различни неща.
const SYNONYMS = [
  [['резервно копие', 'резервни копия'], 'бекъп', 'в целия панел се ползва „бекъп"'],
  [['обновление', 'обновления'], 'ъпдейт', 'секцията се казва „Ъпдейти"'],
  [['логин'], 'вход', 'бутонът и секцията ползват „вход"'],
];
for (const { f, text } of files) {
  for (const [wrong, right, why] of SYNONYMS) {
    for (const w of wrong) {
      if (new RegExp(`['\`][^'\`]*\\b${w}\\b`, 'i').test(text)) {
        soft.push(`${f}: ползва „${w}", а другаде е „${right}" — ${why}`);
      }
    }
  }
}

// ── 5. Речникът: празни или подозрителни преводи ─────────────────────────────
{
  const dict = fs.readFileSync(path.join(ROOT, 'public/i18n-dict.js'), 'utf8');
  const rows = [...dict.matchAll(/^\s{2}\[('(?:[^'\\]|\\.)*'), ('(?:[^'\\]|\\.)*'), ('(?:[^'\\]|\\.)*')\],?$/gm)];
  for (const [, bg, en, it] of rows) {
    const [b, e, i] = [bg, en, it].map((x) => x.slice(1, -1));
    if (!e.trim() || !i.trim()) hard.push(`речник: празен превод за „${b.slice(0, 50)}"`);
    // Кирилица в „английския" превод обикновено значи недовършен ред — но не
    // винаги. Три случая са ВЯРНОТО решение и са изброени поименно, за да не се
    // приемат наум: име на език (показва се в собствената си азбука — така се
    // прави навсякъде), триезичен етикет, и български ЛИТЕРАЛ, който кодът
    // наистина записва (суфиксът на копието при смяна на порт).
    const CYRILLIC_OK = new Map([
      ['Български', 'име на език — показва се в собствената си азбука'],
      ['БГ', 'бутонът за език е един и същ на трите езика'],
      ['Език / Language / Lingua', 'етикетът е триезичен по замисъл'],
      ['Всеки пипнат файл получава копие със суфикс „.преди-смяна-на-порт".',
        'суфиксът е ЛИТЕРАЛ, който кодът записва (src/portchange.js) — превод би счупил търсенето'],
    ]);
    if (!CYRILLIC_OK.has(b)) {
      if (/[а-яА-Я]/.test(e)) hard.push(`речник: английският превод на „${b.slice(0, 40)}" съдържа кирилица`);
      if (/[а-яА-Я]/.test(i)) hard.push(`речник: италианският превод на „${b.slice(0, 40)}" съдържа кирилица`);
    }
    // Броят на маркерите ⟦N⟧ трябва да съвпада — иначе преводът губи стойност.
    const cnt = (s) => (s.match(/⟦\d+⟧/g) || []).length;
    if (cnt(b) !== cnt(e) || cnt(b) !== cnt(i)) {
      hard.push(`речник: „${b.slice(0, 40)}" има ${cnt(b)} маркера, преводите — ${cnt(e)}/${cnt(i)}`);
    }
  }
}

if (hard.length) {
  console.error(`✘ Текстови несъответствия — ${hard.length}:`);
  hard.forEach((h) => console.error('  ·', h));
}
if (soft.length) {
  console.log(`\nℹ За човешко око — ${soft.length}:`);
  soft.slice(0, 20).forEach((s) => console.log('  ·', s));
  if (soft.length > 20) console.log(`  … и още ${soft.length - 20}`);
}
if (hard.length) process.exit(1);
console.log('\n✔ Съгласуване по число и терминология — чисто (типографията е за човешко око, виж горе).');
