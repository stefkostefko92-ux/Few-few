// frontend/src/version.js
// ЕДИН източник на версията, показвана в интерфейса.
//
// Защо съществува: страничната лента показваше закован низ „v2.3 SUPREME“, докато
// `package.json` беше на 3.1.0 — тоест продуктът обявяваше на клиента версия, с
// която е разминат с цял мажор. Такъв низ никой не помни да обнови, защото не се
// чупи нищо, когато остарее.
//
// `__APP_VERSION__` се подава от Vite при билд (виж `vite.config.js`), директно от
// `package.json`. Резервната стойност важи само за тестова среда, където define-ът
// не е сглобен.
export const APP_VERSION =
  typeof __APP_VERSION__ !== "undefined" ? __APP_VERSION__ : "0.0.0-dev";

/** „v3.2.0“ — за местата, където показваме версия пред потребител. */
export const APP_VERSION_LABEL = `v${APP_VERSION}`;

// Кодово име на изданието. Показва се до версията в страничната лента.
// Сменя се СЪЗНАТЕЛНО, при мажорно издание — не на всеки patch.
export const RELEASE_NAME = "SUPREMACY";
